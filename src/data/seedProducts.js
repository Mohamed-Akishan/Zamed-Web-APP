const NO_IMAGE = '/images/no-image.svg';

export const normalizeSeedProduct = (product = {}) => {
  const price = Number(product.price) || 0;
  const originalPrice =
    product.originalPrice == null
      ? price
      : Number(product.originalPrice) || price;

  const image = product.image || NO_IMAGE;

  return {
    id: product.id || `seed-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    name: product.name || 'Unnamed Product',
    price,
    originalPrice,
    category: product.category || 'General',
    gender: String(product.gender || 'men').toLowerCase(),
    sizes: Array.isArray(product.sizes) ? product.sizes : [],
    colors: Array.isArray(product.colors) ? product.colors : [],
    stock: Number(product.stock) || 0,
    description: product.description || '',
    details: product.details || '',
    shipping: product.shipping || '',
    brand: product.brand || 'Zamed Premium',
    image: /^https?:\/\//i.test(image) || image.startsWith('/') || image.startsWith('data:image/') || image.startsWith('blob:')
      ? image
      : NO_IMAGE,
    isFeatured: Boolean(product.isFeatured),
    isNewArrival: Boolean(product.isNewArrival),
    rating: Number(product.rating) || 4.5,
    inStock: product.inStock !== false,
    tags: Array.isArray(product.tags) ? product.tags : [],
    createdAt: product.createdAt || new Date().toISOString(),
    updatedAt: product.updatedAt || new Date().toISOString(),
  };
};

